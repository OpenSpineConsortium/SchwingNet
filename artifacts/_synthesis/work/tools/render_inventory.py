"""Render artifacts/_synthesis/inventory.md from inventory.json, so the table and the
records never disagree: the JSON is the record, the Markdown is read by people."""
import json
import sys


ASCII_MAP = {"\u2013": "-", "\u2014": "-", "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"', "\u2026": "...",
             "\u00d7": "x", "\u2264": "<=", "\u2265": ">=", "\u00b1": "+/-", "\u2192": "->", "\u2190": "<-", "\u00a0": " ",
             "\u2022": "-", "\u00b7": ".", "\u2212": "-", "\u00e9": "e", "\u00e8": "e", "\u00fc": "u", "\u00f6": "o", "\u00e4": "a",
             "\u00b0": " degrees", "\u00b5": "u", "\u03bc": "u", "\u2248": "~", "\u2260": "!=", "\u00ae": "(R)", "\u2122": "(TM)"}


def to_ascii(text):
    for k, v in ASCII_MAP.items():
        text = text.replace(k, v)
    return text.encode("ascii", "replace").decode("ascii")


def cell(s):
    return str(s if s is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def short(s, n):
    s = cell(s)
    return s if len(s) <= n else s[: n - 3].rstrip() + "..."


def main(src, dst):
    inv = json.load(open(src, encoding="utf-8"))
    recs = inv["artifacts"]
    out = []
    out.append("# Artifact inventory\n")
    out.append(inv["about"] + "\n")
    out.append(f"{len(recs)} artifacts inventoried ({sum(1 for r in recs if r['repo']=='SchwingNet')} in SchwingNet, "
               f"{sum(1 for r in recs if r['repo']=='symphony-template')} in symphony-template); "
               f"{len(inv['skipped'])} skipped as not copied. Generated by the synthesis of {inv['date']} from inventory.json; "
               "edit the JSON and render again rather than editing this file.\n")
    out.append("## Table\n")
    out.append("| # | Artifact | Repository | Account | Kind | Date | Question it answers | Claims | Numbers | Decisions | Confidentiality |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for i, r in enumerate(recs, 1):
        link = f"[{cell(r['title'])}](../../{r['folder']}/)" if r["repo"] == "SchwingNet" else f"[{cell(r['title'])}](https://github.com/OpenSpineConsortium/symphony-template/tree/main/artifacts/{r['folder']}/)"
        out.append(f"| {i} | {link} | {r['repo']} | {cell(r['account'])} | {r['kind']}, {cell(r['genre'])} | {cell(r['date'])} | "
                   f"{short(r['question'], 160)} | {len(r['key_claims'])} | {len(r['numbers'])} | {len(r['decisions'])} | {r['confidentiality']} |")
    out.append("\n## Skipped (not copied into the repository; not inventoried)\n")
    for s in inv["skipped"]:
        out.append(f"- {cell(s['title'])} ({cell(s['account'])}): {cell(s['folder_cell'])}")
    out.append("\n## Records\n")
    out.append("One block per artifact: the question, the summary, the key claims with their grade hint, the numbers that carry the strongest claims, the decisions, the open questions and the related artifacts. The full lists are in inventory.json.\n")
    for i, r in enumerate(recs, 1):
        out.append(f"### {i}. {cell(r['title'])}\n")
        out.append(f"- Folder: `{r['repo']}/artifacts/{r['folder']}`; account: {cell(r['account'])}; link id: {cell(r['link_id'])}; {r['kind']}, {cell(r['genre'])}; date: {cell(r['date'])} ({short(r['date_evidence'], 120)}); confidentiality: {r['confidentiality']}.")
        out.append(f"- Question: {cell(r['question'])}")
        out.append(f"- Summary: {cell(r['summary'])}")
        if r["key_claims"]:
            out.append("- Key claims:")
            for c in r["key_claims"][:12]:
                out.append(f"  - ({c['grade_hint']}) {cell(c['claim'])}")
        if r["numbers"]:
            out.append(f"- Numbers ({len(r['numbers'])} recorded; the first {min(10, len(r['numbers']))} here):")
            for n in r["numbers"][:10]:
                extra = "".join([f", n = {cell(n['n'])}" if n.get("n") else "", f", interval {cell(n['interval'])}" if n.get("interval") else ""])
                out.append(f"  - {cell(n['value'])} {cell(n['unit'])}{extra}: {short(n['context'], 140)}")
        if r["datasets"] or r["tools"] or r["models"]:
            out.append(f"- Datasets: {', '.join(map(cell, r['datasets'])) or 'none named'}; tools: {', '.join(map(cell, r['tools'])) or 'none named'}; models: {', '.join(map(cell, r['models'])) or 'none named'}.")
        if r["decisions"]:
            out.append("- Decisions:")
            for d in r["decisions"][:10]:
                when = f" ({cell(d['date'])})" if d.get("date") else ""
                who = f", {cell(d['owner'])}" if d.get("owner") else ""
                out.append(f"  - {cell(d['decision'])}{when}{who}" + (f": {short(d['reason'], 160)}" if d.get("reason") else ""))
        if r["open_questions"]:
            out.append("- Open questions: " + " / ".join(short(q, 160) for q in r["open_questions"][:8]))
        if r["stale_markers"]:
            out.append("- Stale markers: " + " / ".join(short(q, 120) for q in r["stale_markers"][:8]))
        if r["related_titles"]:
            out.append("- Related: " + "; ".join(f"{cell(x['title'])} ({x['relation']})" for x in r["related_titles"][:10]))
        if r.get("coverage_notes"):
            out.append(f"- Coverage: {short(r['coverage_notes'], 300)}")
        out.append("")
    text = "\n".join(out) + "\n"
    text = to_ascii(text)
    open(dst, "w", encoding="ascii", newline="\n").write(text)
    print(dst, len(text), "bytes")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
