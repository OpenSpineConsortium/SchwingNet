@beartype
@ensure(lambda result: len(result) == 90, "three heights, six offsets and five rotations")
@ensure(lambda result: len(set(result)) == len(result), "no pose twice")
def pose_grid() -> list[tuple[int, int, int]]:
    """The 90 fixed poses as (y mm, z mm, alpha degrees), in the order the heights, offsets and
    rotations are listed."""
    return [(y, z, alpha) for y in POSE_Y_MM for z in POSE_Z_MM for alpha in POSE_ALPHA_DEG]


@beartype
@require(lambda pose_id: 0 <= pose_id < 90, "a pose id counts the grid from 0")
@ensure(lambda result: result in pose_grid(), "one of the grid's poses")
def pose_of(pose_id: int) -> tuple[int, int, int]:
    """The pose a FluXray sample's pose_id names, counted as pose_grid lists them."""
    return pose_grid()[pose_id]


@beartype
@require(lambda values: 1 <= len(values) <= 1_000_000, "a sample of 1 to a million values")
@require(lambda values: all(math.isfinite(v) for v in values), "finite values")
@require(lambda q: 0.0 <= q <= 1.0, "a quantile between 0 and 1")
@ensure(lambda result, values: min(values) <= result <= max(values), "within the sample's range")
def quantile(values: Sequence[float], q: float) -> float:
    """The q-quantile with linear interpolation between order statistics, as numpy's default
    reads it."""
    ordered = sorted(values)
    position = q * (len(ordered) - 1)
    below = math.floor(position)
    above = min(below + 1, len(ordered) - 1)
    weight = position - below
    low, high = ordered[below], ordered[above]
    # The two products round on their own, so their sum can land a few ulps outside the pair it
    # interpolates (-2.2 twice gave -2.2000000000000006); the clamp keeps the promise above.
    return min(max(low * (1.0 - weight) + high * weight, low), high)


@beartype
@require(lambda deltas: 1 <= len(deltas) <= 1_000_000, "a pose group of 1 to a million samples")
@require(lambda deltas: all(math.isfinite(d) for d in deltas), "finite differences")
@require(lambda q: 0.5 <= q <= 1.0, "the high quantile the paper reflects, 0.98")
@ensure(lambda result: math.isfinite(result), "a finite cut-off")
def keep_cutoff(deltas: Sequence[float], q: float = FLUXRAY.filter_quantile) -> float:
    """The lower bound a pose group's paired soft-Dice difference must reach to be kept.

    FluXray's rule, in its README's spelling: delta = SoftDice(edited) - SoftDice(raw) from the
    segmenter trained on raw DRRs alone, and the bound is the high tail reflected about the
    median, 2 * median - q98, so a sample whose edit hurt the segmentation more than the best
    helped is dropped. The paper spells the same rule with the sign reversed.
    """
    return 2.0 * quantile(deltas, 0.5) - quantile(deltas, q)


@beartype
@require(lambda deltas: 1 <= len(deltas) <= 1_000_000, "a pose group of 1 to a million samples")
@require(lambda deltas: all(math.isfinite(d) for d in deltas), "finite differences")
@ensure(lambda result, deltas: len(result) == len(deltas), "one answer per sample")
@ensure(
    lambda result, deltas: result[max(range(len(deltas)), key=lambda i: deltas[i])],
    "the best edit is kept",
)
def kept(deltas: Sequence[float]) -> list[bool]:
    """Which samples of one pose group the paired filter keeps: those at or above the cut-off."""
    bound = keep_cutoff(deltas)
    return [d >= bound for d in deltas]


@beartype
@require(
    lambda sdd_mm, sod_mm: 0.0 < sod_mm < sdd_mm <= 10_000.0,
    "the source is nearer the isocentre than the detector",
)
@ensure(lambda result: result > 1.0, "a cone beam magnifies")
def magnification(sdd_mm: float, sod_mm: float) -> float:
    """How much larger the detector draws a thing at the isocentre, SDD over SOD."""
    return sdd_mm / sod_mm


@beartype
@require(lambda spacing_mm: 0.0 < spacing_mm <= 10.0, "a detector pixel of up to 10 mm")
@require(
    lambda sdd_mm, sod_mm: 0.0 < sod_mm < sdd_mm <= 10_000.0,
    "the source is nearer the isocentre than the detector",
)
@ensure(lambda result, spacing_mm: 0.0 < result < spacing_mm, "smaller than the detector's pixel")
def pixel_at_isocentre_mm(spacing_mm: float, sdd_mm: float, sod_mm: float) -> float:
    """What one detector pixel spans at the isocentre, the detector's pixel over the
    magnification."""
    return spacing_mm / magnification(sdd_mm, sod_mm)


@beartype
@require(
    lambda width_px: 1 <= width_px <= 100_000, "an endplate one to a hundred thousand pixels wide"
)
@ensure(lambda result: 0.0 < result <= 45.0, "a positive angle, at most 45 degrees")
def angle_quantum_deg(width_px: int) -> float:
    """The smallest change of an endplate's angle a mask can show: one pixel of rise over its
    width."""
    return math.degrees(math.atan(1.0 / width_px))


@beartype
@require(lambda width_mm: 0.0 < width_mm <= 1000.0, "a width up to a metre")
@require(lambda pixel_mm: 0.001 <= pixel_mm <= 10.0, "a pixel of a micrometre to 10 mm")
@ensure(lambda result: result >= 1, "at least one pixel")
def width_px(width_mm: float, pixel_mm: float) -> int:
    """How many pixels a width spans, at least one."""
    return max(1, round(width_mm / pixel_mm))


# A lumbar endplate is about 45 mm wide on the AP view (Panjabi's morphometry), the width the
# angle quantum is read over.
ENDPLATE_WIDTH_MM = 45.0


@beartype
@require(
    lambda recipe: max(POSE_Y_MM) < recipe.render_sdd_mm <= 10_000.0,
    "a detector beyond the farthest source height",
)
@require(
    lambda recipe: 0.1 <= recipe.render_spacing_mm <= 1.0,
    "a detector pixel of 0.1 to 1 mm, so the 256-pixel canvas of a 1024 render stays under 4 mm",
)
@require(
    lambda recipe: (
        recipe.render_pixels in (256, 512, 768, 1024) and recipe.stored_pixels in (256, 512, 1024)
    ),
    "the sizes a recipe may name",
)
@ensure(
    lambda result: len(result) == 2 * len(POSE_Y_MM), "one row per height at each of the two sizes"
)
@ensure(
    lambda result: all(0.0 < r["pixel_mm"] < 5.0 for r in result),
    "pixels under 5 mm at the isocentre",
)
def measurement_rows(recipe: EditRecipe = FLUXRAY) -> list[dict[str, float | int]]:
    """What a pixel and an endplate's angle come to at the stored and the rendered size, pose by
    pose.

    The source heights are the SOD; the detector is at SDD; a 256-pixel canvas of the same field
    has a pixel four times the rendered one. The endplate column says what the review's "too
    coarse for measurement" means: the angle one pixel of rise changes over a 45 mm endplate.
    """
    rows = []
    for pixels in (recipe.stored_pixels, recipe.render_pixels):
        spacing = recipe.render_spacing_mm * recipe.render_pixels / pixels
        for sod in POSE_Y_MM:
            pixel = pixel_at_isocentre_mm(spacing, recipe.render_sdd_mm, float(sod))
            rows.append(
                {
                    "pixels": pixels,
                    "sod_mm": sod,
                    "magnification": round(magnification(recipe.render_sdd_mm, float(sod)), 3),
                    "pixel_mm": round(pixel, 3),
                    "endplate_px": width_px(ENDPLATE_WIDTH_MM, pixel),
                    "angle_quantum_deg": round(
                        angle_quantum_deg(width_px(ENDPLATE_WIDTH_MM, pixel)), 2
                    ),
                }
            )
    return rows


@beartype
@require(lambda subject: 1 <= len(subject) <= 200 and subject.isascii(), "a subject key in ASCII")
@require(lambda pose_id: 0 <= pose_id < 90, "a pose of the grid")
@require(lambda arm: 0 <= arm <= 1000, "an arm or repeat, 0 to 1000")
@ensure(lambda result: 0 <= result < 2**31, "a seed a generator takes")
def seed_for(subject: str, pose_id: int, arm: int = 0) -> int:
    """The seed one (subject, pose, arm) edits with, from a digest, so a rerun draws the same
    noise."""
    digest = hashlib.sha256(
        f"schwingnet-realism|{subject}|{pose_id}|{arm}".encode("ascii")
    ).digest()
    return int.from_bytes(digest[:4], "big") % (2**31)


@beartype
@require(
    lambda auc_low, auc_high: 0.0 <= auc_low <= auc_high <= 1.0,
    "an interval inside 0 to 1, low end first",
)
@require(lambda mmd_q: 0.0 <= mmd_q <= 1.0, "a p-value, or its q over several spaces")
@require(
    lambda reference_auc_high: 0.0 <= reference_auc_high <= 1.0,
    "FluXray's own split-half upper bound",
)
@ensure(lambda result: result in VERDICTS, "one of the four words")
def verdict(auc_low: float, auc_high: float, mmd_q: float, reference_auc_high: float) -> str:
    """The word for one comparison, from the classifier's interval and the MMD's p-value, or
    its Benjamini-Hochberg q where several feature spaces are read at once.

    Separable: the classifier beats 0.6 even at its lower bound. Matched: the classifier does no
    better than FluXray's own split halves against each other, and MMD does not reject.
    Indistinguishable: the lower bound is at or under 0.6 and MMD does not reject. Undecided:
    the two tests disagree.
    """
    if auc_low > INDISTINGUISHABLE_AUC:
        return "separable"
    if mmd_q >= MMD_ALPHA and auc_high <= max(reference_auc_high, CHANCE_AUC):
        return "matched"
    if mmd_q >= MMD_ALPHA:
        return "indistinguishable"
    return "undecided"


