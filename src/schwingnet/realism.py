@beartype
@ensure(lambda result: all(isinstance(line, str) and line for line in result), "each said in words")
@ensure(lambda result, recipe: recipe != FLUXRAY or not result, "the paper's recipe holds")
def recipe_problems(recipe: EditRecipe) -> list[str]:
    """Every way a recipe falls outside what exists, in words; empty when it holds."""
    return [said for holds, said in RECIPE_RULES if not holds(recipe)]


