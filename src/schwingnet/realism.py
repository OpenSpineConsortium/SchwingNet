"""The FLUX.2 edit that made FluXray, as a record, and the rules of its reproduction.

The owner's ask of 2026-10-25: find CSAIL's trained Flux Realism and finetune it until it makes
X-rays numerically indistinguishable from FleXray's Hugging Face dataset, resolution first. What
CSAIL released is no trained model: FluXray (the "Enhanced DRRs" of arXiv 2609.26756, FleXray's
paper) is FLUX.2 [klein] 9B used as it ships, zero-shot, on raw DRRs rendered from the MOOSE CTs,
with one prompt, four denoising steps and two filters, and the paper says it "needs no
task-specific fine-tuning". So the reproducible object is the recipe, kept here word for word,
and the finetune is ours: a LoRA edit adapter on a klein model trained on (raw DRR, target)
pairs, whose target is FluXray itself, an edit by the 9B model or, where pairs exist, a real
frame. This module holds what needs no torch and no network, so the gate proves it and the tools
and the grid job read one copy:

- the recipe: the prompt as the paper prints it, the model, the steps, the guidance, the
  rendering geometry (1024 pixels, SDD 1250 mm, 0.6 mm pixels, the volume's centre as isocentre),
  the 90 fixed poses (three source heights, six vertical offsets, five rotations about the long
  axis) and the two filters (the foreground floor and the paired soft-Dice rule);
- the models a finetune may start from, each with its licence and whether its weights are gated,
  since the FLUX Non-Commercial License (9B, base-9B) and Apache 2.0 (4B, base-4B) decide what
  the project may own (docs/research/flux-realism/README.md);
- the filter rule as a function, so the tool and the tests agree on the cut-off;
- the resolution arithmetic: what a pixel spans at the isocentre under each pose, what an
  endplate's angle is quantised to at 256 and 1024 pixels, which is what the review's "256 x 256
  masks are too coarse for measurement" means in degrees;
- the pre-registered words of the comparison (matched, indistinguishable, undecided, separable)
  and the rule that chooses one from the two-sample classifier's interval and the MMD's p-value,
  fixed here before any number exists;
- the LoRA training configuration, every hyperparameter named once, which tools/realism.py writes
  for the trainer so a run is reproducible from this file and a seed;
- the stages of the grid word `realism <stage>` (grid/gate.sh, grid/realism.sbatch), each one job;
- the replication's plan (ReplicationPlan): the model, how the CTs and their poses are drawn by
  seed, the arms, the statistics' sizes, and the lines of PREREG.md's frozen block that the flow
  (flows/realism.py) holds the code to before it runs.

Resolution comes first: FluXray is stored at 256 pixels, which is FleXray's inference canvas and
not the data's limit, so the edit here runs at the model's native 1024 and keeps the renderer's
exact 1024-pixel masks beside every image; the comparison to FluXray goes through FleXray's own
256-pixel preprocessing, since that is the only size FluXray exists at.
"""

