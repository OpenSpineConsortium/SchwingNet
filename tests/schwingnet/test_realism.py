def test_the_verdict_words_are_fixed_and_follow_the_two_tests():
    assert VERDICTS == ("matched", "indistinguishable", "undecided", "separable")
    assert (CHANCE_AUC, INDISTINGUISHABLE_AUC, MMD_ALPHA) == (0.5, 0.6, 0.05)
    # the classifier beats 0.6 at its lower bound: separable, whatever MMD says
    assert verdict(0.61, 0.7, 0.9, 0.55) == "separable"
    # no better than FluXray against its own halves, and MMD does not reject: matched
    assert verdict(0.48, 0.55, 0.3, 0.55) == "matched"
    assert verdict(0.45, 0.5, 0.3, 0.4) == "matched"
    # within 0.6 but above FluXray's own halves, MMD not rejecting: indistinguishable
    assert verdict(0.52, 0.58, 0.3, 0.55) == "indistinguishable"
    # the classifier cannot tell them apart but MMD can: the tests disagree
    assert verdict(0.5, 0.6, 0.01, 0.55) == "undecided"


def test_the_models_name_their_licences_and_the_default_base_is_one_the_project_may_keep():
    assert set(MODELS) == {"klein-9b", "klein-4b", "klein-base-9b", "klein-base-4b"}
    for name, model in MODELS.items():
        assert model["repo"].startswith("black-forest-labs/FLUX.2-klein")
        assert model["gated"] is (not model["commercial"]), name
        assert (model["licence"] == "Apache-2.0") is model["commercial"], name
        assert model["toolkit_arch"] == f"flux2_klein_{model['parameters_b']}b"
    assert MODELS[DEFAULT_BASE]["commercial"] and not MODELS[DEFAULT_BASE]["distilled"]
    assert FLUXRAY.model == "klein-9b" and not MODELS["klein-9b"]["commercial"]


def test_the_lora_plan_is_pre_registered_and_its_configuration_names_every_number_once():
    plan = LoraPlan()
    assert lora_problems(plan) == []
    assert (plan.base, plan.rank, plan.learning_rate, plan.steps, plan.resolution) == (
        DEFAULT_BASE,
        16,
        1e-4,
        2000,
        1024,
    )
    assert plan.target in LORA_TARGETS
    config = lora_config(plan, "/pairs", "/out")
    process = config["config"]["process"][0]
    assert process["model"]["name_or_path"] == MODELS[DEFAULT_BASE]["repo"]
    assert process["model"]["arch"] == "flux2_klein_4b"
    assert process["network"] == {"type": "lora", "linear": 16, "linear_alpha": 16}
    assert process["datasets"][0]["folder_path"] == "/pairs/target"
    assert process["datasets"][0]["control_path"] == "/pairs/control"
    assert process["datasets"][0]["resolution"] == [1024]
    assert process["train"]["lr"] == 1e-4 and process["train"]["seed"] == plan.seed
    assert process["save"]["save_every"] == 250
    assert json.loads(json.dumps(config)) == config
    other = lora_config(LoraPlan(seed=7, rank=32), "/pairs", "/out")
    assert other["config"]["name"] != config["config"]["name"]


