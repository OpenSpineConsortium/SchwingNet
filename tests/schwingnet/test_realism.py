def test_quantile_reads_as_numpy_does():
    assert quantile([3.0, 1.0, 2.0], 0.5) == 2.0
    assert quantile([1.0, 2.0, 3.0, 4.0], 0.5) == 2.5
    assert quantile([1.0, 2.0, 3.0, 4.0], 0.0) == 1.0
    assert quantile([1.0, 2.0, 3.0, 4.0], 1.0) == 4.0
    assert quantile([10.0], 0.98) == 10.0
    assert math.isclose(quantile([0.0, 1.0], 0.98), 0.98)


def test_quantile_stays_inside_a_pair_of_equal_order_statistics():
    # -2.2 * 0.7 + -2.2 * 0.3 rounds to -2.2000000000000006 in binary floating point, below the
    # sample's minimum; the postcondition would fail without the clamp.
    values = [0.7, 0.001, 0.001, -2.2, -2.2]
    assert quantile(values, 0.02) == -2.2
    assert quantile([0.001, -2.2, -2.2, 0.001, 3.0], 0.5) == 0.001
    for q in (0.02, 0.3, 0.5, 0.98):
        assert min(values) <= quantile(values, q) <= max(values)


def test_the_filter_reflects_the_high_tail_about_the_median_and_keeps_the_best():
    # the README's rule: delta = edited - raw, keep delta >= 2 * median - q98
    deltas = [0.0, 0.01, -0.01, 0.02, 0.5, -0.5]
    bound = keep_cutoff(deltas)
    assert math.isclose(bound, 2 * quantile(deltas, 0.5) - quantile(deltas, 0.98))
    answer = kept(deltas)
    assert answer == [d >= bound for d in deltas]
    # the bound reflects the 0.5 gain to about -0.44, so -0.5 is dropped and the rest are kept
    assert answer == [True, True, True, True, True, False]
    assert -0.45 < bound < -0.43
    # one sample is always kept, and an all-equal group keeps every sample
    assert kept([0.3]) == [True]
    assert kept([0.1, 0.1, 0.1]) == [True, True, True]


def test_the_resolution_arithmetic_says_what_256_pixels_cost_in_degrees():
    assert math.isclose(magnification(1250.0, 650.0), 1250 / 650)
    assert math.isclose(pixel_at_isocentre_mm(0.6, 1250.0, 650.0), 0.6 * 650 / 1250)
    assert width_px(45.0, 0.312) == 144
    assert width_px(0.1, 1.0) == 1
    assert math.isclose(angle_quantum_deg(1), 45.0)
    assert angle_quantum_deg(144) < 0.5 < 1.5 < angle_quantum_deg(36)
    rows = measurement_rows()
    assert [r["pixels"] for r in rows] == [256, 256, 256, 1024, 1024, 1024]
    stored, rendered = rows[0], rows[3]
    assert stored["sod_mm"] == rendered["sod_mm"] == 650
    assert math.isclose(stored["pixel_mm"], 4 * rendered["pixel_mm"], rel_tol=0.01)
    # at the stored size a one-pixel rise over a lumbar endplate is already above one degree
    assert all(r["angle_quantum_deg"] > 1.0 for r in rows if r["pixels"] == 256)
    assert all(r["angle_quantum_deg"] < 1.0 for r in rows if r["pixels"] == 1024)


